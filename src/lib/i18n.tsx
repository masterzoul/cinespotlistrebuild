export type Messages = (typeof messages)["ms"];
type I18nValue = Messages;
const I18nContext = createContext<{ language: Language; setLanguage: (language: Language) => void; t: I18nValue }>({ language: "ms", setLanguage: () => undefined, t: messages.ms });

export function getStoredLanguage(): Language {
  if (typeof window === "undefined") return "ms";
  const value = window.localStorage.getItem(LANGUAGE_KEY);
  return value === "en" || value === "ar" ? value : "ms";
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<Language>("ms");
  useEffect(() => setLanguageState(getStoredLanguage()), []);
  useEffect(() => {
    document.documentElement.lang = language;
    document.documentElement.dir = language === "ar" ? "rtl" : "ltr";
  }, [language]);
  const value = useMemo(() => ({
    language,
    setLanguage: (next: Language) => {
      setLanguageState(next);
      window.localStorage.setItem(LANGUAGE_KEY, next);
    },
    t: messages[language] as I18nValue,
  }), [language]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export const useI18n = () => useContext(I18nContext);
